#!/usr/bin/env python3
"""emoji-list: the Emoji plugin's list, made from Unicode's emoji-test.txt.

    python3 tools/emoji-list.py path/to/emoji-test.txt

Writes plugins/emoji/Emojis.js: every fully qualified emoji in Unicode's order, in its
Unicode category, with its name as words to search by. Skin tone variants are left
out (one emoji each), and so is the Components group (tones and hair on their own).
Extra words the list already had ("lol", "adore") are kept.

emoji-test.txt: https://unicode.org/Public/emoji/<version>/emoji-test.txt
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "plugins", "emoji", "Emojis.js")

# Unicode's groups, as the picker names them
GROUPS = {
    "Smileys & Emotion": ("smileys", "Smileys", "\U0001F600"),
    "People & Body": ("people", "People", "\U0001F44B"),
    "Animals & Nature": ("nature", "Nature", "\U0001F43B"),
    "Food & Drink": ("food", "Food", "\U0001F354"),
    "Travel & Places": ("travel", "Travel", "\U0001F697"),
    "Activities": ("activities", "Activities", "⚽"),
    "Objects": ("objects", "Objects", "\U0001F4A1"),
    "Symbols": ("symbols", "Symbols", "❤️"),
    "Flags": ("flags", "Flags", "\U0001F3C1"),
}
TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$")


def old_words():
    """the words the list had for each emoji, to keep searching by them"""
    if not os.path.exists(OUT):
        return {}
    src = open(OUT, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r'\["([^"]+)",\s*"([^"]*)"(?:,\s*"([^"]*)")?', src):
        # this file's own lines: [emoji, name, extra words, category]; older ones: [emoji, words]
        out[m.group(1)] = (m.group(3) if m.group(3) is not None and not m.group(3) in ("smileys", "people", "nature", "food", "travel", "activities", "objects", "symbols", "flags") else m.group(2))
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    keep = old_words()
    group, out, seen = None, [], set()
    for line in open(sys.argv[1], encoding="utf-8"):
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        m = LINE.match(line.strip())
        if not m or group not in GROUPS:
            continue
        cps = "".join(chr(int(c, 16)) for c in m.group(1).split())
        if any(ch in TONES for ch in cps) or cps in seen:
            continue
        seen.add(cps)
        name = m.group(3).strip().lower()
        name = re.sub(r"^flag: ", "flag ", name)
        words = re.sub(r"[^\w\s'&.-]", " ", name)
        words = " ".join(words.split())
        extra = [w for w in keep.get(cps, "").split() if w not in words.split()]
        out.append([cps, words, " ".join(extra), GROUPS[group][0]])
    cats = [{"key": k, "label": l, "glyph": g} for k, l, g in GROUPS.values()]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/emoji-list.py from Unicode's emoji-test.txt: every emoji,\n")
        fh.write("// one per kind (no skin tone variants), in Unicode's order. Don't edit by hand.\n")
        fh.write(".pragma library\n\n")
        fh.write("// the categories, in order: { key, label, glyph }\n")
        fh.write("var categories = " + json.dumps(cats, ensure_ascii=False) + ";\n\n")
        fh.write("// [emoji, its name, more words to find it by, its category]\n")
        fh.write("var list = [\n")
        for e in out:
            fh.write("    " + json.dumps(e, ensure_ascii=False) + ",\n")
        fh.write("];\n")
    by = {}
    for e in out:
        by[e[3]] = by.get(e[3], 0) + 1
    print("%d emoji: %s" % (len(out), ", ".join("%s %d" % (k, by.get(k, 0)) for k, _, _ in GROUPS.values())))


if __name__ == "__main__":
    main()
