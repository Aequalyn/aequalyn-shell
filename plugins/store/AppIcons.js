// One icon policy for every app card: a real image when the icon set has it,
// and a locally generated badge for everything else. No 404 requests.
function url(icon, name) {
    var i = String(icon || "").trim();
    if (/^(?:\/|https?:|file:|data:)/i.test(i)) return i;
    var cp = i.charCodeAt(0);
    if (cp >= 0xE000 && cp <= 0xF8FF) i = "";
    if (i && has(i)) return "https://cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons/png/" + i + ".png";
    return badge(name || i || "app");
}
