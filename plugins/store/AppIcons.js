var available = {};
for (var i = 0; i < names.length; i++) available[names[i]] = true;

function has(name) {
    return !!available[String(name || "").trim().toLowerCase()];
}

function hash(name) {
    var s = String(name || "a").toLowerCase();
    var h = 0;
    for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 1000000007;
    return h;
}

function hue(name) {
    return hash(name) % 360;
}

function initials(name) {
    var words = String(name || "?").trim().split(/\s+/).filter(Boolean);
    if (words.length === 0) return "?";
    if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
    return (words[0].charAt(0) + words[1].charAt(0)).toUpperCase();
}

function escapeXml(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;")
        .replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

// A local SVG badge keeps every app visually distinct even when no publisher
// icon exists. Each name gets its own hue and initials, with no network call.
function badge(name) {
    var label = escapeXml(initials(name));
    var h = hue(name);
    var svg = '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">' +
        '<rect width="64" height="64" rx="14" fill="hsl(' + h + ', 42%, 42%)"/>' +
        '<text x="32" y="40" font-family="sans-serif" font-size="21" font-weight="700" ' +
        'text-anchor="middle" fill="#ffffff">' + label + '</text></svg>';
    return "data:image/svg+xml," + encodeURIComponent(svg);
}

